/**
 * Builds `src/docs/content.gen.ts` from the guides in `docs/site/` and the app's tokens (HAL-3773).
 * The Worker can't read files at run time, so the guides' Markdown and the token stylesheet are
 * written into a module it imports. `--check` fails when the module is out of date, so `bun run check`
 * catches a guide edited without a rebuild.
 *
 *   bun tools/docs/build.ts          write the module
 *   bun tools/docs/build.ts --check  exit 1 if it would change
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const root = join(import.meta.dir, "../..")
const siteDir = join(root, "docs/site")
const out = join(root, "src/docs/content.gen.ts")

type Guide = { slug: string; title: string; summary: string; markdown: string }

/** `01-index.md` → "" (the docs home), `02-getting-started.md` → "getting-started". */
const slugOf = (file: string) => {
  const slug = file.replace(/^\d+-/, "").replace(/\.md$/, "")
  return slug === "index" ? "" : slug
}

/** Splits the front matter (`summary:`, required) from the page. */
const parse = (file: string, source: string) => {
  const front = /^---\n([\s\S]*?)\n---\n+/.exec(source)
  const summary = front?.[1] && /^summary:\s*(.+)$/m.exec(front[1])?.[1]?.trim()
  if (!front || !summary) throw new Error(`${file}: start with front matter that has a summary: line`)
  return { summary, markdown: source.slice(front[0].length) }
}

export const readGuides = (): Array<Guide> =>
  readdirSync(siteDir)
    .filter((f) => /^\d+-.+\.md$/.test(f))
    .sort()
    .map((file) => {
      const { summary, markdown } = parse(
        file,
        readFileSync(join(siteDir, file), "utf8").replace(/\r\n/g, "\n"),
      )
      const title = /^# (.+)\n/.exec(markdown)?.[1]?.trim()
      if (!title) throw new Error(`${file}: the page must start with a "# Title" heading`)
      return { slug: slugOf(file), title, summary, markdown }
    })

/** The app's token sheet (web/src/styles/tokens.css): the docs pages use the same values. */
const tokensCss = () =>
  readFileSync(join(root, "web/src/styles/tokens.css"), "utf8")
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\n\s*\n/g, "\n")
    .trim()

const render = () => {
  const guides = readGuides()
  const slugs = new Set<string>()
  for (const g of guides) {
    if (slugs.has(g.slug)) throw new Error(`two guides have the slug "${g.slug}"`)
    slugs.add(g.slug)
  }
  return `// Generated by tools/docs/build.ts from docs/site/*.md and web/src/styles/tokens.css. Don't edit:
// change the source and run \`bun run docs:build\`.

export interface Guide {
  /** The page's path under /docs: "" is the docs home. */
  readonly slug: string
  readonly title: string
  /** One sentence from the page's front matter: used in /llms.txt, the nav and the page's description. */
  readonly summary: string
  /** The page, with {{origin}} where the install's origin goes. */
  readonly markdown: string
}

export const GUIDES: ReadonlyArray<Guide> = ${JSON.stringify(guides, null, 2)}

export const TOKENS_CSS = ${JSON.stringify(tokensCss())}
`
}

if (import.meta.main) {
  const next = render()
  let current = ""
  try {
    current = readFileSync(out, "utf8")
  } catch {}
  if (process.argv.includes("--check")) {
    if (current !== next) {
      console.error("src/docs/content.gen.ts is out of date: run `bun run docs:build`.")
      process.exit(1)
    }
    console.log("docs: content.gen.ts is up to date")
  } else {
    writeFileSync(out, next)
    console.log(`docs: wrote ${readGuides().length} guides to src/docs/content.gen.ts`)
  }
}
